"""
Connes adele alternative: brief numerical sketch.

Connes (1999) proposed a non-commutative geometry on A_Q / Q* whose
scaling-action generator has eigenvalues coinciding with the zeta zeros.
We model a finite local approximation:

  D = log(p) * a_p^dag a_p   on the Fock space generated by primes p < P_max
  with measure exp(-s * log p) -> p^{-s}.

Multiplicative semigroup of N under the scaling Z* -> Z*. Then characteristic
log spectrum eigenvalues map (after the von Mangoldt unfolding) to:

  sum_{p, k}  log(p) / p^{ks}  =  -d/ds log zeta(s) = -zeta'(s)/zeta(s)

The zeros of zeta appear as POLES of zeta'/zeta. So the local Connes operator
"sees" the zeros indirectly through the log-derivative.

We compute this in a truncated way and report basic properties; the framework's
R_f(3/2, .) modulation would replace zeta(s) -> R_f(3/2, s) - log derivative.
"""
from __future__ import annotations
import numpy as np
from sympy import primerange
from bbm_framework import R_f


def log_deriv_zeta_truncated(s: complex, P_max: int = 200, K: int = 8) -> complex:
    """  -zeta'(s)/zeta(s) ~ sum_{p<P_max} sum_{k=1..K} log(p)/p^(ks).  """
    primes = list(primerange(2, P_max))
    total = 0.0 + 0.0j
    for p in primes:
        for k in range(1, K + 1):
            total += np.log(p) / (p ** (k * s))
    return total


def log_deriv_Rf_truncated(alpha: float, s: complex, N: int = 4000,
                           eps: float = 1e-6) -> complex:
    """ Finite-difference d/ds R_f via central differences on R_f. """
    return (R_f(alpha, s + eps, N) - R_f(alpha, s - eps, N)) / (2 * eps) \
        / R_f(alpha, s, N)


def survey():
    print("Truncated -zeta'/zeta vs framework R_f log-derivative on the critical line")
    print("-" * 78)
    sigma = 0.5
    test_t = [14.135, 21.022, 25.011, 30.425, 32.935,  # known zero ordinates
              17.0, 23.0, 28.0]  # off-zero check
    header = "{:>10}  {:>30}  {:>32}".format("t", "-zeta'/zeta", "-Rf'/Rf (alpha=3/2)")
    print(header)
    for t in test_t:
        s = sigma + 1j * t
        z = log_deriv_zeta_truncated(s)
        r = log_deriv_Rf_truncated(1.5, s, N=4000)
        print(f"{t:>10.3f}  {z.real:>14.4f}+{z.imag:>+13.4f}i  "
              f"{r.real:>14.4f}+{r.imag:>+13.4f}i")


if __name__ == "__main__":
    survey()
