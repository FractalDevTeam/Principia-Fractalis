#!/usr/bin/env python3
"""
Emit the march schedule from the D=1 band edge to c = 13, as committed data.

WHY A TABLE RATHER THAN LIVE PROBING. Choosing (r, D) per box by trial
generation would cost 3-8 producer runs per box, and at D = 16 a run emits
~100 files. A precomputed schedule is cheaper, inspectable, reviewable in a
diff, and -- the point -- it cannot drift from the priced ladder, because it IS
the priced ladder.

It is not trusted, either: gen_box.py asserts `Q*r < Mc_lb` at generate time
and REFUSES to emit a pilot when the criterion fails. So the schedule is a
proposal and the producer is the gate. If a row is wrong the march stops on
that row with measured numbers, which is the designed behaviour.

SCHEME. `mmrrrr` at every density: midpoint on the sub-segments covering
[0, 1/2], range-brick on the rest. Every midpoint sub-segment then has
T <= 1/2 = Tier A, the only tier the emitted M-bound proof supports, so no new
tier is needed at any density. Measured (price7) to reach c = 13 at every
centre, at a 2-4x density premium over the per-segment optimum.

CONSERVATISM. The model prices each BASE segment's midpoint error with that
segment's own T, while the producer uses each SUB-segment's T, which is smaller
and therefore gives a smaller M and a tighter enclosure. So the producer is
never worse than this model. Checked: at c = 41/4, D = 2 the model says
Mc_lb = 0.02033509 and the producer computes 0.02033508.

COST MODEL. A box at density D compiles 6D + 1 panel modules -- 6D
sub-segments plus Seg01Range as a definitional dependency of the add-ons --
plus CoreDefs, four add-ons and the assemble. Measured at 7m30s per panel
module and ~3 min for the rest, i.e. (6D + 1)*7.5 + 3 minutes, which reproduced
box 1's observed 56.7 min at D = 1.
"""
import io
import os
import sys
from fractions import Fraction as F

import mpmath as mp

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from price7 import mc_lb_scheme                      # noqa: E402
from price_density import L0_val                      # noqa: E402

mp.mp.dps = 30

SCHEME = "mmrrrr"
DLAD = [1, 2, 4, 8, 16, 32]
RLAD = [F(1, 16), F(1, 32), F(1, 64)]
SAFETY = mp.mpf("1.25")
MIN_PER_MODULE = 7.5
START = F(161, 16)        # 10.0625, the D=1 band edge
TARGET = F(13)


def Q_of(c, r):
    """The rational majorant of L0(c-r) that the emitted Lean actually uses
    (R1BoxLocalLNumeric.L0_le_rat, from omega(1) <= 1/22)."""
    x = c - r
    return F(1, 11) * (1 + 1 / x) + F(1, 2) / x ** 2


def feasible(c, r, D):
    """The criterion the producer asserts, with the 1.25x safety the radius
    ladder uses. Note it is Q, not the tight L0: the emitted proof carries the
    1/22 majorant, so pricing against L0 would be optimistic."""
    m = mc_lb_scheme(c, D, SCHEME)
    qr = Q_of(c, r) * r          # Q*r, not Q: the criterion is Q*r < Mc_lb
    return m > SAFETY * (mp.mpf(qr.numerator) / qr.denominator), m, qr


def main():
    rows = []
    f = START
    guard = 0
    while f < TARGET and guard < 400:
        guard += 1
        best = None
        for r in RLAD:
            c = f + r
            for D in DLAD:
                ok, m, qr = feasible(c, r, D)
                if ok:
                    cost = (6 * D + 1) * MIN_PER_MODULE + 3.0
                    key = cost / (2.0 * float(r))
                    if best is None or key < best[0]:
                        best = (key, c, r, D, m, qr, cost)
                    break          # smallest feasible D at this radius
        if best is None:
            print(f"# STOP: no (r, D) in the ladders reaches past "
                  f"{float(f):.6f}", file=sys.stderr)
            break
        _, c, r, D, m, qr, cost = best
        rows.append((c, r, D, m, qr, cost))
        f = c + r

    out = io.StringIO()
    out.write("# march schedule: D=1 band edge -> c = 13\n")
    out.write("# generated by codex/make_schedule.py -- a PROPOSAL; gen_box.py\n")
    out.write("# asserts Q*r < Mc_lb at generate time and refuses infeasible rows.\n")
    out.write("# columns: centre radius density  (Mc_lb, Q*r, ratio, est_minutes)\n")
    tot = 0.0
    mods = 0
    for c, r, D, m, qr, cost in rows:
        tot += cost
        mods += 6 * D + 1
        out.write(f"{c} {r} {D}"
                  f"   # Mc_lb={float(m):.8f} Qr={float(qr):.8f}"
                  f" ratio={float(m)/float(qr):.1f}x est={cost:.0f}min\n")
    io.open("march_schedule.txt", "w", encoding="utf-8",
            newline="\n").write(out.getvalue())

    print(f"{len(rows)} boxes, frontier {float(f):.6f}, "
          f"{mods} panel modules, {tot/60:.1f} h")
    print()
    grp = {}
    for c, r, D, m, qr, cost in rows:
        grp.setdefault(D, []).append((float(c), str(r)))
    print(f"{'D':>3} {'boxes':>6} {'c range':>22} {'radii':>16} {'h':>7}")
    for D in sorted(grp):
        cs = [x[0] for x in grp[D]]
        rs = sorted(set(x[1] for x in grp[D]), key=lambda s: -eval(s))
        h = len(cs) * ((6 * D + 1) * MIN_PER_MODULE + 3.0) / 60
        print(f"{D:>3} {len(cs):>6} "
              f"[{min(cs):>8.4f},{max(cs):>8.4f}] {','.join(rs):>16} {h:>7.1f}")
    print()
    print(f"  wrote march_schedule.txt ({len(rows)} rows)")


if __name__ == "__main__":
    main()
