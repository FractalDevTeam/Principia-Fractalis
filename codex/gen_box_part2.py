UNCOND_TPL = "R1_c27_4_r1_16_pointwise_UNCONDITIONAL_2026_10_19.lean"

# (lo_edge, hi_edge) of the c = 27/4, r = 1/16 template
TPL_C = F(27, 4)
TPL_R = F(1, 16)
TPL_RATS = ["4510553327 / 320000000000", "4802446903 / 320000000000",
            "161621101 / 320000000000", "21496359 / 16000000000"]


def emit_uncond_pilot(c, r, tag, lean_frac, retag, here, outdir, tots):
    """Textual port of the 1000-line edge-identity chain. The box-edge
    fractions are routed through placeholders: at c = 27/4 the edges are
    107/16 and 109/16, and 109/16 is the LOWER edge at c = 55/8 -- an ordered
    substitution would alias them."""
    t, tt = tag(c), tag(TPL_C)
    rt = f"r{r.numerator}_{r.denominator}"
    src = io.open(os.path.join(here, UNCOND_TPL), encoding="utf-8").read()
    s = src

    # 1. module paths whose DATE changes (longest first)
    renames = [
        (f"PF.Analytic.PilotBoxes.R1_{tt}_r1_16_HYBRID_2026_10_19",
         f"PF.Analytic.PilotBoxes.R1_{t}_{rt}_HYBRID_2026_10_20"),
        (f"PF.Analytic.FourierPanels.Assemble_{tt}_threehalves_HYBRID_2026_10_19",
         f"PF.Analytic.FourierPanels.Assemble_{t}_threehalves_HYBRID_2026_10_20"),
        (f"PF.Analytic.FourierPanels.ResidueBound_{tt}_three_halves_to_5_2026_10_19",
         f"PF.Analytic.FourierPanels.ResidueBound_{t}_three_halves_to_5_2026_10_20"),
        (f"PF.Analytic.FourierPanels.ResidueBoundTight_{tt}_2026_10_19",
         f"PF.Analytic.FourierPanels.ResidueBoundTight_{t}_2026_10_20"),
        (f"PF.Analytic.FourierPanels.AnalyticTailBound_{tt}_2026_10_19",
         f"PF.Analytic.FourierPanels.AnalyticTailBound_{t}_2026_10_20"),
        (f"PF.Analytic.FourierPanels.OmegaTailBound_{tt}_2026_10_19",
         f"PF.Analytic.FourierPanels.OmegaTailBound_{t}_2026_10_20"),
        (f"Seg01Midpoint_{tt}_2026_10_17", f"Seg01Midpoint_{t}_2026_10_20"),
        (f"Seg02Midpoint_{tt}_2026_10_17", f"Seg02Midpoint_{t}_2026_10_20"),
        # namespaces of the gate pilot and the assemble
        (f"PilotR1Box_{tt}_r1_16_HYBRID_20261019",
         f"PilotR1Box_{t}_{rt}_HYBRID_20261020"),
        (f"PilotR1Box_{tt}_r1_16_pointwise_UNCONDITIONAL_20261019",
         f"PilotR1Box_{t}_{rt}_pointwise_UNCONDITIONAL_20261020"),
        (f"R1_{tt}_r1_16_pointwise_UNCONDITIONAL_2026_10_19",
         f"R1_{t}_{rt}_pointwise_UNCONDITIONAL_2026_10_20"),
        # the gate pilot's theorem names were simplified in the generated version
        (f"pilot_r1_box_{tt}_r1_16_closed", "pilot_r1_box_closed"),
        (f"gate1_arithmetic_{tt}_hybrid", "gate1_arithmetic_hybrid"),
    ]
    for a, b in renames:
        s = s.replace(a, b)

    # 2. box edges, via placeholders (109/16 aliases across c)
    lo_t, hi_t = lean_frac(TPL_C - TPL_R), lean_frac(TPL_C + TPL_R)
    lo_n, hi_n = lean_frac(c - r), lean_frac(c + r)
    assert s.count(lo_t) > 0 and s.count(hi_t) > 0, "pilot: template edges absent"
    s = s.replace(lo_t, "@@LOEDGE@@").replace(hi_t, "@@HIEDGE@@")
    # 3. the four hybrid rationals -> the new enclosure
    for old, new in zip(TPL_RATS, [lean_frac(x) for x in tots]):
        assert old in s, f"pilot: template rational {old} absent"
        s = s.replace(old, new)
    # 4. everything else c-dependent
    s = retag(s, TPL_C, c, is_python=False)
    # 5. radius, then expand the edge placeholders
    if r != TPL_R:
        s = re.sub(r"(?<![0-9.])1/16(?![0-9.])", lean_frac(r), s)
    s = s.replace("@@LOEDGE@@", lo_n).replace("@@HIEDGE@@", hi_n)
    assert "@@" not in s, "pilot: unexpanded placeholder"

    # 6. The pilot carries its OWN `gate1_arithmetic` with the fixed 3/4 target
    #    baked in, in both the statement and the `show` that feeds norm_num.
    #    That target is false from c = 29/4 on, so retarget it at the COMPUTED
    #    gate value -- the same value emit_assemble now states. Anchored on the
    #    two proof-term occurrences so the `3/4` in the surrounding prose is
    #    left alone (it is rewritten separately below).
    ADDON = F(7, 10**7) + F(12, 10**8) + F(1, 10**21)
    gate = c * c * (tots[1] + ADDON) + c * (tots[3] + ADDON)
    for a, b, desc in (
            ("      ≤ 3/4 := by" + LF, f"      ≤ {lean_frac(gate)} := by" + LF,
             "gate1_arithmetic statement"),
            ("      ≤ 3/4" + LF + "  norm_num",
             f"      ≤ {lean_frac(gate)}" + LF + "  norm_num",
             "gate1_arithmetic show")):
        n = s.count(a)
        assert n == 1, f"pilot: {desc} found {n} times, expected 1"
        s = s.replace(a, b)
    # the prose that quotes the old target, so the file does not contradict itself
    s = s.replace("≤ 3/4`", f"≤ {lean_frac(gate)}`")
    s = s.replace("gate-1 margin = 3/4 −",
                  f"gate-1 margin (old fixed shape) = 3/4 −")
    assert "≤ 3/4 :=" not in s, "pilot: a fixed-3/4 target survived"

    s = s.replace("SPDX-License-Identifier: Apache-2.0",
                  f"Emitted by codex/gen_box.py --c {lean_frac(c)} --r {lean_frac(r)} "
                  f"(2026-10-20)." + LF + LF + "SPDX-License-Identifier: Apache-2.0", 1)
    path = os.path.join(outdir, f"R1_{t}_{rt}_pointwise_UNCONDITIONAL_2026_10_20.lean")
    io.open(path, "w", encoding="utf-8", newline=LF).write(s)
    return path
