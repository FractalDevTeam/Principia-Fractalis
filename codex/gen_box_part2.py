def emit_gate_pilot(c, r, tag, lean_frac, outdir, R_ub, I_ub, margin):
    """The box goes through `box_of_enclosure_rat` (R1BoxLocalLNumeric,
    89a5fdb1): the PARAMETERISED criterion `L0(c-r)*r < Mc_lb` with the local
    `L0 ~ 0.11`, not the old fixed `Mc_lb = 1/8` with `L = 1`.

    The old shape needed `r < 1/8` and `gate <= 3/4`; the latter is FALSE from
    c = 29/4 on, which is where it stopped the march. What is asserted now is
    the real criterion, with the same 1.25x safety the radius ladder uses."""
    t = tag(c)
    rt = f"r{r.numerator}_{r.denominator}"
    ADDON = F(7, 10**7) + F(12, 10**8) + F(1, 10**21)
    gate = c * c * (R_ub + ADDON) + c * (I_ub + ADDON)
    mclb = (F(1) - gate) / 2
    # Rational majorant of L0(c-r), matching R1BoxLocalLNumeric.L0_le_rat:
    #   L0 x <= (1/11)(1 + 1/x) + 1/(2 x^2),   since omega(1) <= 1/22.
    Q = F(1, 11) * (1 + 1 / (c - r)) + F(1, 2) / (c - r) ** 2
    assert Q * r < mclb, (
        f"box criterion fails at c = {c}, r = {r}: Q*r = {float(Q*r):.8f} "
        f"is not < Mc_lb = {float(mclb):.8f}")
    assert c + r <= 14, (
        f"box edge {c+r} exceeds the Gate-2 reach 14 of the log-weighted bound")
    lo, hi = c - r, c + r
