def _parse_midpoint_literals(c, tag, outdir):
    """Read back the EMITTED midpoint files and recover each panel's lo/hi
    literal exactly as written. Parsing the emitted text (rather than
    re-deriving it) guarantees the `have b : ... := Seg0sMidpoint...` type
    ascription in the assemble matches byte-for-byte; a mismatch there would be
    a defeq failure at elaboration, not a numeric error."""
    import re as _re
    PANEL_WIDTH, MID_SEGS, RANGE_SEGS = _geom()
    t = tag(c)
    out = {}
    for s_idx in MID_SEGS:
        path = os.path.join(outdir, f"{seg_mod_mid(s_idx)}_{t}_2026_10_20.lean")
        txt = io.open(path, encoding="utf-8").read()
        pat = (r"theorem m(\d+)p(\d+)_(plus|minus)_integral_bound\s*:\s*"
               r"\((-?[0-9.]+) : ℝ\)\s*≤\s*\(∫ u in \((-?[0-9.]+) : ℝ\)\.\."
               r"\((-?[0-9.]+) : ℝ\),[^)]*\)\s*∧[^≤]*≤\s*\((-?[0-9.]+) : ℝ\)")
        n = 0
        for m in _re.finditer(pat, txt, _re.DOTALL):
            sg, pk, side, lo, _a, _b, hi = m.groups()
            out[(side, int(sg), int(pk))] = (lo, hi)
            n += 1
        assert n == 2 * N_PANELS, (
            f"midpoint parse: seg{s_idx} found {n} panels, expected {2*N_PANELS}")
    return out


